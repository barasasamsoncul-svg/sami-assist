
-- SaMi customer support tickets and conversation history.
-- Customers can create requests and follow replies.
-- Admin users can manage tickets and respond.
-- Internal notes are never exposed to customer accounts.

CREATE TABLE IF NOT EXISTS public.support_tickets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

  public_code text NOT NULL UNIQUE
    CHECK (length(trim(public_code)) BETWEEN 8 AND 40),

  customer_id uuid NOT NULL
    REFERENCES public.users(id) ON DELETE CASCADE,

  related_errand_id uuid
    REFERENCES public.errands(id) ON DELETE SET NULL,

  category text NOT NULL
    CHECK (category IN (
      'errand',
      'payment',
      'account',
      'technical',
      'other'
    )),

  subject text NOT NULL
    CHECK (length(trim(subject)) BETWEEN 5 AND 160),

  status text NOT NULL DEFAULT 'open'
    CHECK (status IN (
      'open',
      'in_progress',
      'waiting_customer',
      'resolved',
      'closed'
    )),

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  resolved_at timestamptz
);

CREATE INDEX IF NOT EXISTS support_tickets_customer_recent_idx
  ON public.support_tickets(customer_id, created_at DESC);

CREATE INDEX IF NOT EXISTS support_tickets_status_updated_idx
  ON public.support_tickets(status, updated_at DESC);


CREATE TABLE IF NOT EXISTS public.support_ticket_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  ticket_id uuid NOT NULL
    REFERENCES public.support_tickets(id) ON DELETE CASCADE,

  sender_id uuid
    REFERENCES public.users(id) ON DELETE SET NULL,

  sender_role text NOT NULL
    CHECK (sender_role IN ('customer', 'admin')),

  message text NOT NULL
    CHECK (length(trim(message)) BETWEEN 1 AND 4000),

  is_internal boolean NOT NULL DEFAULT false,

  created_at timestamptz NOT NULL DEFAULT now(),

  CHECK (sender_role = 'admin' OR is_internal = false)
);

CREATE INDEX IF NOT EXISTS support_ticket_messages_thread_idx
  ON public.support_ticket_messages(ticket_id, created_at ASC);

