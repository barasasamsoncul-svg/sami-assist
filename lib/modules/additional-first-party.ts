import {
  defineSamiModule,
  type SamiModuleCategory,
  type SamiModuleManifest,
} from '@/lib/modules/types';

/*
 * Additional first-party SaMi module foundations.
 *
 * These 44 modules extend the original 36 to one canonical 80-app catalog.
 * They intentionally match the same platform/framework maturity as the
 * original module foundations: installable schema + dependency contract +
 * generic workspace route. Their full business pages, permissions, services,
 * workflows, reports and AI extensions are implemented later app-by-app.
 */

const NO_EXTENSIONS = {
  dashboard: false,
  search: false,
  notifications: false,
  activity: false,
  automationTriggers: false,
  automationActions: false,
  aiTools: false,
  integrationProviders: false,
  apiEndpoints: false,
} as const;

function additionalModule({
  key,
  name,
  description,
  category,
  icon,
  depends,
  optionalDepends,
}: {
  key: string;
  name: string;
  description: string;
  category: SamiModuleCategory;
  icon: string;
  depends: string[];
  optionalDepends: string[];
}): SamiModuleManifest {
  return defineSamiModule({
    key,
    name,
    version: '1.0.0',
    description,
    category,
    icon,
    route: `apps/${key}`,
    application: true,
    installable: true,
    autoInstall: false,
    recommended: false,
    depends,
    optionalDepends,
    schemaPath: `lib/apps/${key}/schema.sql`,
    migrationNamespace: key,
    navigation: [
      {
        key: `${key}.root`,
        label: name,
        href: `/apps/${key}`,
        iconKey: icon,
        parentKey: null,
        actionKey: `${key}.open`,
        order: 10,
      },
    ],
    actions: [
      {
        key: `${key}.open`,
        name: `Open ${name}`,
        type: 'route',
        href: `/apps/${key}`,
        viewKeys: [
          `${key}.workspace`,
        ],
        target: 'current',
      },
    ],
    views: [
      {
        key: `${key}.workspace`,
        name: `${name} workspace`,
        type: 'workspace',
        route: `/apps/${key}`,
        priority: 10,
      },
    ],
    resources: [],
    security: {
      permissions: [],
      recordPolicies: [],
      fieldPolicies: [],
    },
    settings: [],
    extensions: {
      ...NO_EXTENSIONS,
    },
  });
}

